 Conversor de Celsius para Fahrenheit
 */

import Playgrounds

#Playground {

// 1. Criação uma variável para armazenar a temperatura em Celsius
    let celsius = 32.0
    
// 2. Conversão para Fahrenheit
    var fahrenheit = (celsius * 9 / 5) + 32

// 3. Impressão do resultado, com a temperatura em Celsius e em Fahrenheit
    print("A temperatura em Celsius é de \(celsius)ºC e em Fahrenheit é de \(fahrenheit)ºF")
}
